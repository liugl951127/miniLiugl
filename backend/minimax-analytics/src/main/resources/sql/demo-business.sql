SET MODE MySQL;
SET NAMES utf8mb4;

-- ============================================================
-- 用户表
-- ============================================================
CREATE TABLE IF NOT EXISTS demo_user (
    user_id       BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '用户ID',
    user_name     VARCHAR(64) NOT NULL COMMENT '用户名',
    real_name     VARCHAR(128) COMMENT '真实姓名',
    email         VARCHAR(256) COMMENT '邮箱',
    phone         VARCHAR(32) COMMENT '手机号',
    gender        VARCHAR(8) COMMENT 'M/F/OTHER',
    age           INT COMMENT '年龄',
    city          VARCHAR(64) COMMENT '所在城市',
    level         INT DEFAULT 1 COMMENT '会员等级 1-5',
    balance       DECIMAL(12,2) DEFAULT 0.00 COMMENT '账户余额',
    status        VARCHAR(16) DEFAULT 'ACTIVE' COMMENT 'ACTIVE/FROZEN/BANNED',
    created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

-- ============================================================
-- 商品类别表
-- ============================================================
CREATE TABLE IF NOT EXISTS demo_category (
    category_id     BIGINT AUTO_INCREMENT PRIMARY KEY,
    category_name   VARCHAR(128) NOT NULL COMMENT '类目名称',
    parent_id       BIGINT COMMENT '父类目ID，顶级为NULL',
    sort_order      INT DEFAULT 0 COMMENT '排序',
    icon_url        VARCHAR(512) COMMENT '类目图标',
    description     VARCHAR(512) COMMENT '描述',
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- ============================================================
-- 商品表
-- ============================================================
CREATE TABLE IF NOT EXISTS demo_product (
    product_id      BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '商品ID',
    product_name    VARCHAR(256) NOT NULL COMMENT '商品名称',
    category_id     BIGINT COMMENT '所属类目',
    brand           VARCHAR(128) COMMENT '品牌',
    price           DECIMAL(10,2) NOT NULL COMMENT '售价',
    cost            DECIMAL(10,2) COMMENT '成本价',
    stock           INT DEFAULT 0 COMMENT '库存数量',
    sold_count      INT DEFAULT 0 COMMENT '已售数量',
    rating          DECIMAL(3,2) DEFAULT 5.00 COMMENT '评分 1-5',
    review_count    INT DEFAULT 0 COMMENT '评价数',
    tags            VARCHAR(512) COMMENT '标签，逗号分隔',
    status          VARCHAR(16) DEFAULT 'ONLINE' COMMENT 'ONLINE/OFFLINE/DELETED',
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

-- ============================================================
-- 订单表
-- ============================================================
CREATE TABLE IF NOT EXISTS demo_order (
    order_id        VARCHAR(32) PRIMARY KEY COMMENT '订单号',
    user_id         BIGINT NOT NULL COMMENT '下单用户',
    order_status    VARCHAR(32) DEFAULT 'PENDING' COMMENT 'PENDING/PAID/SHIPPED/DELIVERED/COMPLETED/CANCELLED/REFUNDED',
    total_amount    DECIMAL(12,2) NOT NULL COMMENT '订单总额',
    discount_amount DECIMAL(10,2) DEFAULT 0.00 COMMENT '优惠金额',
    pay_amount      DECIMAL(12,2) NOT NULL COMMENT '实付金额',
    pay_method      VARCHAR(32) COMMENT 'WECHAT/ALIPAY/CARD/CASH/POINTS',
    pay_time        TIMESTAMP COMMENT '支付时间',
    shipping_fee    DECIMAL(8,2) DEFAULT 0.00 COMMENT '运费',
    receiver_name   VARCHAR(128) COMMENT '收货人',
    receiver_phone  VARCHAR(32) COMMENT '收货电话',
    receiver_address VARCHAR(512) COMMENT '收货地址',
    remark          VARCHAR(512) COMMENT '买家备注',
    order_date      DATE NOT NULL COMMENT '下单日期（分区字段）',
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE INDEX idx_order_user ON demo_order(user_id);
CREATE INDEX idx_order_date ON demo_order(order_date);
CREATE INDEX idx_order_status ON demo_order(order_status);

-- ============================================================
-- 订单明细表
-- ============================================================
CREATE TABLE IF NOT EXISTS demo_order_item (
    item_id         BIGINT AUTO_INCREMENT PRIMARY KEY,
    order_id        VARCHAR(32) NOT NULL COMMENT '所属订单',
    product_id      BIGINT NOT NULL COMMENT '商品ID',
    product_name   VARCHAR(256) COMMENT '商品快照名称',
    category_id     BIGINT COMMENT '类目快照',
    sku_code        VARCHAR(64) COMMENT 'SKU编码',
    unit_price      DECIMAL(10,2) NOT NULL COMMENT '单价',
    quantity        INT NOT NULL COMMENT '购买数量',
    total_amount    DECIMAL(12,2) NOT NULL COMMENT '小计金额',
    discount_amount DECIMAL(10,2) DEFAULT 0.00 COMMENT '优惠分摊',
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_item_order ON demo_order_item(order_id);
CREATE INDEX idx_item_product ON demo_order_item(product_id);

-- ============================================================
-- 支付记录表
-- ============================================================
CREATE TABLE IF NOT EXISTS demo_payment (
    payment_id      VARCHAR(32) PRIMARY KEY COMMENT '支付流水号',
    order_id        VARCHAR(32) NOT NULL COMMENT '关联订单',
    user_id         BIGINT NOT NULL COMMENT '付款用户',
    amount          DECIMAL(12,2) NOT NULL COMMENT '支付金额',
    pay_method      VARCHAR(32) NOT NULL COMMENT 'WECHAT/ALIPAY/CARD',
    transaction_id  VARCHAR(128) COMMENT '第三方交易号',
    pay_status      VARCHAR(16) DEFAULT 'SUCCESS' COMMENT 'SUCCESS/FAILED/PENDING/REFUNDED',
    pay_time        TIMESTAMP NOT NULL COMMENT '支付时间',
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_pay_order ON demo_payment(order_id);
CREATE INDEX idx_pay_user ON demo_payment(user_id);

